/**
 * The generated rules, with no packages (#1593). The load map and the knowledge map say which
 * references load when the work touches which files; this turns each into a path-scoped rule for
 * Claude Code under `.claude/rules/generated/`. The folder is build output: it is ignored by git,
 * and this module rebuilds it wherever it is needed. The session-start hook (a fresh clone, a
 * worktree) and `scripts/agent-context.mjs` both use it, and neither needs `npm ci` first.
 *
 * A copy rather than an import or a symlink, because an `@import` inside a rule loads at session
 * start whatever its `paths` say, and git on Windows checks symlinks out as plain text unless
 * symlinks are enabled (both tested on 2026-11-06, recorded on #144).
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

import {
  KNOWLEDGE_MAP,
  LOAD_MAP,
  globToRegExp,
  parseKnowledgeMap,
  parseLoadMap,
  rulePaths,
  unix,
} from './agent-context-maps.mjs'

export const GENERATED_DIR = '.claude/rules/generated'

/** Turns a relative Markdown link in `text`, written from `source`, into a repo-root link. */
export function rootLinks(text, source) {
  return text.replace(/\]\((?!https?:|mailto:|#|\/)([^)\s]+)\)/g, (_, target) => {
    const [file, hash] = target.split('#')
    const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(source), file))
    return `](/${resolved}${hash === undefined ? '' : `#${hash}`})`
  })
}

/** The generated rule for one reference. */
export function renderRule({ source, paths, text }) {
  const frontmatter = ['---', 'paths:', ...paths.map((glob) => `  - '${glob}'`), '---'].join('\n')
  const notice =
    `<!-- Generated by scripts/agent-context.mjs from ${source}. Edit that file, then run ` +
    '`npm run agent-context -- --write`. -->'
  return `${frontmatter}\n\n${notice}\n\n${rootLinks(text, source).trimEnd()}\n`
}

/** The file name of the generated copy of `source`. */
export function ruleName(source) {
  return `${source.replace(/\.md$/, '').replaceAll('/', '--')}.md`
}

/** The text of a file under `root`, or null when it is not a file. */
export function readFile(root, file) {
  const full = path.join(root, file)
  return fs.existsSync(full) && fs.statSync(full).isFile()
    ? unix(fs.readFileSync(full, 'utf8'))
    : null
}

/** The files git tracks under `root`. The generated folder is not among them. */
export function trackedFiles(root) {
  return execFileSync('git', ['ls-files'], { cwd: root, encoding: 'utf8' }).split('\n')
}

/**
 * The rules the maps produce for the checkout at `root`: a Map of repository path to text, and the
 * problems found on the way (a listed file that is missing, a glob that matches nothing).
 */
export function buildRules(root, tracked = trackedFiles(root)) {
  const problems = []
  const guidelines = parseLoadMap(readFile(root, LOAD_MAP) ?? '').map((entry) => ({
    ...entry,
    origin: LOAD_MAP,
  }))
  if (guidelines.length === 0) problems.push(`${LOAD_MAP} has no load map with globs`)
  const notes = parseKnowledgeMap(readFile(root, KNOWLEDGE_MAP) ?? '[]')

  const rules = new Map()
  for (const entry of [...guidelines, ...notes]) {
    const text = readFile(root, entry.source)
    if (text === null) {
      problems.push(`${entry.origin} lists ${entry.source}, which doesn't exist`)
      continue
    }
    for (const glob of entry.paths) {
      const regexp = globToRegExp(glob)
      if (!tracked.some((file) => regexp.test(file))) {
        problems.push(`${entry.source}: \`${glob}\` matches no file in the repository`)
      }
    }
    rules.set(
      `${GENERATED_DIR}/${ruleName(entry.source)}`,
      renderRule({ ...entry, paths: rulePaths(entry, tracked), text }),
    )
  }
  return { rules, problems }
}

/**
 * Writes the rules into the checkout at `root`, replacing the folder's files and leaving a file
 * alone when it is already current. Returns what `buildRules` found.
 */
export function writeRules(root) {
  const built = buildRules(root)
  const dir = path.join(root, GENERATED_DIR)
  fs.mkdirSync(dir, { recursive: true })
  for (const name of fs.readdirSync(dir)) {
    if (!built.rules.has(`${GENERATED_DIR}/${name}`))
      fs.rmSync(path.join(dir, name), { recursive: true })
  }
  for (const [file, text] of built.rules) {
    if (readFile(root, file) !== text) fs.writeFileSync(path.join(root, file), text)
  }
  return built
}
