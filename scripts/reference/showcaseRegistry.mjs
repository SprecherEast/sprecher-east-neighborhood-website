/**
 * The showcase's import map (#1532): one generated TypeScript file with a lazy `import()` for every
 * shared component and every examples file in the index, so the showcase pages (a static export)
 * can load them by name without a list kept by hand. A bundler can follow only static import
 * paths, which is why it is a file and not something the pages work out.
 */

/** `src/platform/ui/Button.tsx` as the path code imports it by: `@/platform/ui/Button`. */
const importPath = (file) => file.replace(/^src\//, '@/').replace(/\.tsx?$/, '')

export const SHOWCASE_REGISTRY_FILE = 'src/platform/ui/showcaseRegistry.ts'

/** The text of `showcaseRegistry.ts` for an index (the generator formats it). */
export function renderShowcaseRegistry(index) {
  const files = [...new Set(index.components.flatMap((c) => c.examples?.files ?? []))].sort()
  return [
    '// Generated by `npm run docs:generate` from the showcase index (docs/reference/showcase-index.json). Do not edit by hand: add a component or an examples file, then run `npm run docs:generate`.',
    '',
    '/** Loads a module on demand: the pages of the showcase use these, so each page ships only what it shows. */',
    'export type ShowcaseLoader = () => Promise<unknown>',
    '',
    '/** Every shared component, by its exported name. */',
    'export const COMPONENT_LOADERS: Record<string, ShowcaseLoader> = {',
    ...index.components.map(
      (c) => `  ${c.name}: () => import('${importPath(c.file)}').then((m) => m.${c.name}),`,
    ),
    '}',
    '',
    '/** Every examples file, by its path in the repository (the `file` of an example in the index). */',
    'export const EXAMPLES_LOADERS: Record<string, ShowcaseLoader> = {',
    ...files.map((file) => `  '${file}': () => import('${importPath(file)}'),`),
    '}',
    '',
  ].join('\n')
}
