import { describe, expect, it } from 'vitest'

import { describeRoute, renderRoutes, routeUrl } from './routes.mjs'

describe('routeUrl', () => {
  it('turns a page file into its URL pattern and drops route groups', () => {
    expect(routeUrl('page.tsx')).toBe('/')
    expect(routeUrl('events/(index)/category/[category]/page.tsx')).toBe(
      '/events/category/[category]',
    )
    expect(routeUrl('posts/page/[pageNumber]/page.tsx')).toBe('/posts/page/[pageNumber]')
  })

  it('does the same for a route handler', () => {
    expect(routeUrl('api/version/route.ts')).toBe('/api/version')
  })
})

describe('describeRoute', () => {
  const page = `
import type { Metadata } from 'next'
import { draftMode } from 'next/headers'
import { EventListPage } from '@/modules/events/server'
import { eventListTitle } from '@/modules/events'
import { Section } from '@/platform/ui/Section'
import { generateMeta } from '@/platform/seo/generateMeta'

export const revalidate = 600
export function generateStaticParams() { return [] }
export default async function Page() { await draftMode(); return null }
export async function generateMetadata() { return generateMeta({}) }
`

  it('lists the module entry points, once each and sorted', () => {
    expect(describeRoute('events/page.tsx', page).entries).toEqual([
      '@/modules/events',
      '@/modules/events/server',
    ])
  })

  it('reads revalidate, prebuilt params and request-time APIs', () => {
    const row = describeRoute('events/page.tsx', page)
    expect(row.revalidate).toBe('600')
    expect(row.staticParams).toBe(true)
    expect(row.rendering).toBe('reads draftMode')
  })

  it('says where the metadata comes from', () => {
    expect(describeRoute('events/page.tsx', page).metadata).toBe(
      '`generateMetadata` via `@/platform/seo/generateMeta`',
    )
  })

  it('reads a static metadata object and its imports', () => {
    const source = `
import { NOT_INDEXED } from '@/platform/seo/notIndexed'
export const metadata = { title: 'Sign in', ...NOT_INDEXED }
export default function Page() { return null }
`
    expect(describeRoute('login/page.tsx', source).metadata).toBe(
      '`metadata` via `@/platform/seo/notIndexed`',
    )
  })

  it('reports a forced rendering mode and no metadata', () => {
    const source = `export const dynamic = 'force-dynamic'\nexport default function Page() { return null }`
    const row = describeRoute('x/page.tsx', source)
    expect(row.rendering).toBe('dynamic = force-dynamic')
    expect(row.metadata).toBe('inherited from the layout')
    expect(row.revalidate).toBe('')
    expect(row.entries).toEqual([])
  })

  it('lists the HTTP methods of a route handler', () => {
    const source = `export async function POST() {}\nexport async function GET() {}`
    const row = describeRoute('next/seed/route.ts', source)
    expect(row.kind).toBe('route handler')
    expect(row.methods).toEqual(['GET', 'POST'])
  })
})

describe('renderRoutes', () => {
  const rows = [
    {
      url: '/events',
      kind: 'page',
      file: 'events/page.tsx',
      entries: ['@/modules/events/server'],
      rendering: 'not stated',
      revalidate: '600',
      staticParams: false,
      metadata: 'inherited from the layout',
      methods: [],
    },
    {
      url: '/api/version',
      kind: 'route handler',
      file: 'api/version/route.ts',
      entries: [],
      rendering: 'not stated',
      revalidate: '',
      staticParams: false,
      metadata: 'none (no HTML)',
      methods: ['GET'],
    },
  ]

  it('writes the notice, then one table row per route sorted by URL', () => {
    const text = renderRoutes(rows)
    expect(text).toContain('Generated by `npm run docs:generate`')
    const lines = text.split('\n').filter((line) => line.startsWith('| `'))
    expect(lines).toHaveLength(2)
    expect(lines[0]).toContain('`/api/version`')
    expect(lines[1]).toContain('`/events`')
    expect(lines[1]).toContain('`@/modules/events/server`')
    expect(lines[1]).toContain('600')
  })

  it('shows the methods of a handler', () => {
    expect(renderRoutes(rows)).toContain('GET')
  })
})
