import { describe, expect, it } from 'vitest'

import { renderShowcaseRegistry, SHOWCASE_REGISTRY_FILE } from './showcaseRegistry.mjs'

const index = {
  components: [
    {
      name: 'Button',
      file: 'src/platform/ui/Button.tsx',
      examples: {
        files: [
          'src/platform/ui/Button.examples.tsx',
          'src/platform/ui/Button.examples.client.tsx',
        ],
      },
    },
    { name: 'Tabs', file: 'src/platform/ui/Tabs.client.tsx', examples: null },
    {
      name: 'RichText',
      file: 'src/platform/richtext/RichText.tsx',
      examples: { files: ['src/platform/ui/Button.examples.tsx'] },
    },
  ],
}

describe('renderShowcaseRegistry', () => {
  const text = renderShowcaseRegistry(index)

  it('loads each component lazily from its own file, by its name', () => {
    expect(text).toContain("  Button: () => import('@/platform/ui/Button').then((m) => m.Button),")
    expect(text).toContain("  Tabs: () => import('@/platform/ui/Tabs.client').then((m) => m.Tabs),")
    expect(text).toContain(
      "  RichText: () => import('@/platform/richtext/RichText').then((m) => m.RichText),",
    )
  })

  it('loads each examples file once, by its path, sorted', () => {
    const files = text.split('\n').filter((line) => line.includes('.examples'))

    expect(files).toEqual([
      "  'src/platform/ui/Button.examples.client.tsx': () => import('@/platform/ui/Button.examples.client'),",
      "  'src/platform/ui/Button.examples.tsx': () => import('@/platform/ui/Button.examples'),",
    ])
  })

  it('says it is generated, and is the same text every time', () => {
    expect(text.startsWith('// Generated by `npm run docs:generate`')).toBe(true)
    expect(renderShowcaseRegistry(index)).toBe(text)
  })

  it('lives beside the kit', () => {
    expect(SHOWCASE_REGISTRY_FILE).toBe('src/platform/ui/showcaseRegistry.ts')
  })
})
