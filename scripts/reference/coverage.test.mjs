import { describe, expect, it } from 'vitest'

import { buildCoverage, parseElementRows, renderCoverage } from './coverage.mjs'

const HEADER = '| ID | Element | Target component · variant |\n| --- | --- | --- |'
const page = (...rows) => [HEADER, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n')

describe('parseElementRows', () => {
  it('reads the id, the name and the last column of every element row', () => {
    const rows = parseElementRows(
      `# Title\n\n${page(['L1', 'Skip link', 'Button · primary'], ['N2', 'Link', 'Link · nav'])}\n`,
    )
    expect(rows).toEqual([
      { id: 'L1', element: 'Skip link', target: 'Button · primary' },
      { id: 'N2', element: 'Link', target: 'Link · nav' },
    ])
  })

  it('ignores the header, the divider and text that is not a table row', () => {
    expect(parseElementRows(`${HEADER}\n\nL1 is mentioned here.`)).toEqual([])
  })

  it('keeps a pipe inside backticks or escaped in the cell', () => {
    const rows = parseElementRows('| L1 | `a | b` and c \\| d | Text · small |')
    expect(rows[0]).toMatchObject({ element: '`a | b` and c | d', target: 'Text · small' })
  })
})

describe('buildCoverage', () => {
  const row = (id, target) => ({ id, element: id, target })

  it('groups the elements by component and variant, in id order', () => {
    const coverage = buildCoverage([
      row('N10', 'Link · nav'),
      row('N2', 'Link · nav'),
      row('B1', 'Button · primary'),
    ])
    expect(coverage.groups).toEqual([
      { component: 'Button', variant: 'primary', ids: ['B1'] },
      { component: 'Link', variant: 'nav', ids: ['N2', 'N10'] },
    ])
    expect(coverage).toMatchObject({ elements: 3, pairs: 2, components: 2 })
  })

  it('fails on an id that appears twice', () => {
    expect(() => buildCoverage([row('N18', 'Link · nav'), row('N18', 'Link · action')])).toThrow(
      /N18 appears twice/,
    )
  })

  it('fails on an element that names two components or two variants', () => {
    expect(() => buildCoverage([row('C31', 'Text · small; Link · inline')])).toThrow(/C31/)
    expect(() => buildCoverage([row('N18', 'Button · primary / secondary')])).toThrow(/N18/)
  })

  it('fails on an element with no target', () => {
    expect(() => buildCoverage([row('X1', '—')])).toThrow(/X1/)
  })

  it('fails on a malformed id', () => {
    expect(() => buildCoverage([row('7', 'Link · nav')])).toThrow(/"7"/)
  })
})

describe('renderCoverage', () => {
  const text = renderCoverage(
    buildCoverage([
      { id: 'B1', element: 'a', target: 'Button · {appearance}' },
      { id: 'B2', element: 'b', target: 'Button · primary' },
      { id: 'B3', element: 'c', target: 'Button · primary' },
    ]),
  )

  it('starts with a title and the generated notice, and states the counts', () => {
    expect(text).toMatch(/^# /)
    expect(text).toContain('Generated by `npm run docs:generate`')
    expect(text).toContain('3 elements, 2 component-variant pairs, 1 component')
  })

  it('has one row per pair with its ids and count', () => {
    expect(text).toContain('| Button · primary | B2, B3 | 2 |')
    expect(text).toContain('| Button · {appearance} | B1 | 1 |')
  })
})
