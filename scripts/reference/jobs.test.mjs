import { describe, expect, it } from 'vitest'

import { describeCron, describeJobs, jobRoutes, renderJobs } from './jobs.mjs'

describe('describeCron', () => {
  it('says the simple patterns in words', () => {
    expect(describeCron('* * * * *')).toBe('every minute')
    expect(describeCron('*/10 * * * *')).toBe('every 10 minutes')
    expect(describeCron('0 * * * *')).toBe('every hour, on the hour')
    expect(describeCron('15 * * * *')).toBe('every hour at minute 15')
    expect(describeCron('17 7 * * *')).toBe('every day at 07:17')
  })

  it('gives nothing for a pattern it does not read, so the expression stands alone', () => {
    expect(describeCron('0 6 * * 1-5')).toBe('')
    // a fixed hour is not "every minute", and not "every 10 minutes"
    expect(describeCron('* 5 * * *')).toBe('')
    expect(describeCron('*/10 5 * * *')).toBe('')
  })
})

function retain() {}
const locate = (fn) => (fn === retain ? 'src/modules/a/cms/retention.ts' : 'payload')
const config = {
  tasks: [
    {
      slug: 'deleteOld',
      label: 'Delete old things',
      handler: retain,
      schedule: [{ cron: '0 * * * *', queue: 'retention' }],
    },
    { slug: 'schedulePublish', handler: () => ({}) },
  ],
  autoRun: [
    { cron: '*/10 * * * *', queue: 'retention' },
    { cron: '* * * * *', queue: 'default', limit: 10, disableScheduling: true },
  ],
  access: { run: function isAdminBoolean() {}, queue: function isStaff() {} },
}

describe('describeJobs', () => {
  const jobs = describeJobs(config, locate, (file) =>
    file === 'src/modules/a/cms/retention.ts'
      ? [{ collection: 'old-things', operations: ['delete', 'read'] }]
      : [],
  )

  it('describes each task with its schedule, queue, handler file and the collections it reaches', () => {
    expect(jobs.tasks[0]).toMatchObject({
      slug: 'deleteOld',
      label: 'Delete old things',
      schedules: [{ cron: '0 * * * *', words: 'every hour, on the hour', queue: 'retention' }],
      queues: ['retention'],
      file: 'src/modules/a/cms/retention.ts',
      collections: [{ collection: 'old-things', operations: ['delete', 'read'] }],
    })
  })

  it('puts a task nobody schedules in the default queue and marks it as Payload’s own', () => {
    expect(jobs.tasks[1]).toMatchObject({
      slug: 'schedulePublish',
      schedules: [],
      queues: ['default'],
      file: 'payload',
      collections: [],
    })
  })

  it('describes each runner and the tasks in its queue', () => {
    expect(jobs.runners).toEqual([
      {
        cron: '*/10 * * * *',
        words: 'every 10 minutes',
        queue: 'retention',
        limit: '10 (Payload’s default, none is set)',
        schedulingPass: 'yes',
        tasks: ['deleteOld'],
      },
      {
        cron: '* * * * *',
        words: 'every minute',
        queue: 'default',
        limit: '10',
        schedulingPass: 'no',
        tasks: ['schedulePublish'],
      },
    ])
  })

  it('names who may queue and run jobs, in a fixed order, and the endpoint each guards', () => {
    const withRoutes = describeJobs(config, locate, () => [], {
      endpoints: [
        { method: 'GET', path: '/api/payload-jobs/run', guards: 'run' },
        { method: 'GET', path: '/api/payload-jobs/handle-schedules', guards: 'run' },
        { method: 'GET', path: '/api/payload-jobs/count', guards: null },
      ],
    })
    expect(withRoutes.access.map((a) => [a.operation, a.name, a.endpoints])).toEqual([
      ['queue', 'isStaff', []],
      [
        'run',
        'isAdminBoolean',
        ['GET /api/payload-jobs/run', 'GET /api/payload-jobs/handle-schedules'],
      ],
    ])
  })

  it('says the runners are not shown when the config sets them with a function', () => {
    const jobsWithFunction = describeJobs({ ...config, autoRun: () => [] }, locate, () => [])
    expect(jobsWithFunction.runners).toEqual([])
    expect(jobsWithFunction.runnersNote).toMatch(/function/)
    expect(renderJobs(jobsWithFunction, [], extras)).toContain('set by a function')
  })
})

const extras = {
  serverCrons: [{ file: 'ops/install-cron.sh', cron: '15 8 * * *', runs: ['ops/backup.sh daily'] }],
  intelligence: {
    file: 'intelligence/pipeline.yaml',
    cron: '40 6 * * *',
    timezone: 'America/Chicago',
  },
  dependabot: [
    { file: '.github/dependabot.yml', ecosystem: 'npm', directory: '/', when: 'weekly on monday' },
  ],
}

describe('renderJobs', () => {
  const jobs = describeJobs(config, locate, () => [])
  const workflows = [
    { file: '.github/workflows/lint.yml', name: 'Lint', crons: ['0 6 * * *'], jobs: ['Audit'] },
  ]
  const page = renderJobs(jobs, workflows, extras)

  it('starts with the title, then the generated notice', () => {
    expect(page.split('\n')[0]).toBe('# Jobs and schedules')
    expect(page.split('\n')[2]).toMatch(/^> Generated by `npm run docs:generate`/)
  })

  it('lists the server cron, the runner setting and Dependabot, each with its file', () => {
    expect(page).toContain(
      '| `ops/install-cron.sh` | `15 8 * * *` (every day at 08:15) | `ops/backup.sh daily` |',
    )
    expect(page).toContain(
      '| `intelligence/pipeline.yaml` | `40 6 * * *` (every day at 06:40) | America/Chicago |',
    )
    expect(page).toContain('| `.github/dependabot.yml` | npm | `/` | weekly on monday |')
  })

  it('never leaves the reached-collections cell empty: Payload’s own handler, or none found', () => {
    const rows = page.split('\n')
    expect(rows.find((line) => line.startsWith('| `schedulePublish`'))).toContain(
      'Payload’s own handler, not followed',
    )
    expect(rows.find((line) => line.startsWith('| `deleteOld`'))).toContain('none found')
  })

  it('says a task nobody schedules is queued, not scheduled, and writes the schedule of one that is', () => {
    const rows = page.split('\n')
    expect(rows.find((line) => line.startsWith('| `schedulePublish`'))).toContain(
      'queued, not scheduled',
    )
    expect(rows.find((line) => line.startsWith('| `deleteOld`'))).toContain(
      '`0 * * * *` (every hour, on the hour)',
    )
  })

  it('writes the route each job access guards', () => {
    const guarded = describeJobs(config, locate, () => [], {
      endpoints: [{ method: 'GET', path: '/api/payload-jobs/run', guards: 'run' }],
    })
    const page = renderJobs(guarded, workflows, extras)
    expect(page).toContain('| run | `isAdminBoolean` | payload | `GET /api/payload-jobs/run` |')
    expect(page).toMatch(/\| queue \| `isStaff` \|[^|]*\| no route in the config /)
  })

  it('finds the route an access function guards from what the route handler reads', () => {
    const routes = jobRoutes(
      [
        {
          method: 'get',
          path: '/run',
          handler: async (req) => req.payload.config.jobs.access?.run,
        },
        { method: 'get', path: '/handle-schedules', handler: (r) => r.x.jobsConfig.access?.run },
        { method: 'get', path: '/count', handler: function countHandler() {} },
        { method: 'post', path: '/', handler: function createHandler() {} },
      ],
      '/api/payload-jobs',
    )
    expect(routes).toEqual([
      { method: 'GET', path: '/api/payload-jobs/run', guards: 'run' },
      { method: 'GET', path: '/api/payload-jobs/handle-schedules', guards: 'run' },
      { method: 'GET', path: '/api/payload-jobs/count', guards: null },
      { method: 'POST', path: '/api/payload-jobs', guards: null },
    ])
  })

  it('says browser timers and hooks that a write sets off are not shown', () => {
    expect(page).toContain('Timers in browser code')
    expect(page).toContain('hooks a write sets off')
  })

  it('says once which schedules are UTC and which follow the server’s clock', () => {
    expect(page.match(/time zones/gi)).toHaveLength(2)
    expect(page).toContain('the GitHub workflows run in UTC')
    expect(page).toContain('set no time zone, so both follow the server’s clock')
    expect(page).not.toContain('are in UTC')
  })

  it('links each collection a task reaches, lists the calls it counts, and quotes the reasons', () => {
    const reaching = describeJobs(config, locate, (file, name) =>
      name === 'deleteOld'
        ? [
            {
              collection: 'agent-runs',
              operations: ['delete (access bypassed)'],
              why: [{ operation: 'delete', text: 'Nobody is signed in on a schedule.' }],
            },
          ]
        : [],
    )
    const withLinks = renderJobs(reaching, [], extras)
    expect(withLinks).toContain(
      '[`agent-runs`](content-types/agent-runs.md) (delete (access bypassed))',
    )
    expect(withLinks).toContain(
      '- `deleteOld`: `agent-runs`, delete, from the comment on the function that makes the call: Nobody is signed in on a schedule.',
    )
    expect(withLinks).toContain('The calls counted are `find`')
  })

  it('has a row for each task, runner and timed workflow', () => {
    expect(page).toContain('| `deleteOld` |')
    expect(page).toContain('| `retention` | `*/10 * * * *` (every 10 minutes) |')
    expect(page).toContain(
      '| `.github/workflows/lint.yml` | Lint | `0 6 * * *` (every day at 06:00) | Audit |',
    )
  })

  it('points to the hand-written page for tasks outside the repository', () => {
    expect(page).toContain('../knowledge/scheduled-tasks.md')
  })

  it('adds exactly one row when one task is added', () => {
    const more = describeJobs(
      { ...config, tasks: [...config.tasks, { slug: 'extra', handler: retain }] },
      locate,
      () => [],
    )
    const rows = (text) => text.split('\n').filter((line) => line.startsWith('| `')).length
    expect(rows(renderJobs(more, workflows, extras)) - rows(page)).toBe(1)
  })

  it('adds exactly one row when a timed workflow is added', () => {
    const more = [
      ...workflows,
      { file: '.github/workflows/new.yml', name: 'New', crons: ['1 * * * *'], jobs: ['a'] },
    ]
    const rows = (text) =>
      text.split('\n').filter((line) => line.startsWith('| `.github/workflows/')).length
    expect(rows(renderJobs(jobs, more, extras)) - rows(page)).toBe(1)
  })
})
