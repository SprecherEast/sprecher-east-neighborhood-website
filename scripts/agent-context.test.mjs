import { describe, expect, it } from 'vitest'

import {
  globToRegExp,
  hasPaths,
  importsOf,
  parseLoadMap,
  renderRule,
  rootLinks,
  ruleName,
  startupFiles,
} from './agent-context.mjs'

const MAP = `
| Guideline                     | Loads by itself when the work touches | Read it when  |
| ----------------------------- | ------------------------------------- | ------------- |
| [Guard rails](guard-rails.md) | Always                                | Always.       |
| [Payload](payload-cms.md)     | \`src/**/cms/**\`, \`src/payload.config.ts\` | CMS work. |
| [Brand voice](brand-voice.md) | No                                    | Writing.      |
| [Project](../project.md)      | \`src/**\`                            | Code.         |

Not a table row: | [x](x.md) | \`a/**\` |
`

describe('parseLoadMap', () => {
  it('reads the rows whose load column has globs, resolving links from the map', () => {
    expect(parseLoadMap(MAP, 'docs/guidelines/README.md')).toEqual([
      {
        source: 'docs/guidelines/payload-cms.md',
        paths: ['src/**/cms/**', 'src/payload.config.ts'],
      },
      { source: 'docs/project.md', paths: ['src/**'] },
    ])
  })

  it('reads a link with an anchor and a map with Windows line endings', () => {
    const map = MAP.replace('(payload-cms.md)', '(payload-cms.md#collections)').replaceAll(
      '\n',
      '\r\n',
    )
    expect(parseLoadMap(map, 'docs/guidelines/README.md')).toHaveLength(2)
  })

  it('refuses a row it would otherwise drop: a link, no globs, and not "No" or "Always"', () => {
    const map = MAP.replace('| No                ', '| src/app           ')
    expect(() => parseLoadMap(map, 'docs/guidelines/README.md')).toThrow(/brand-voice\.md/)
  })

  it('ignores a table without a load column', () => {
    expect(parseLoadMap('| [A](a.md) | `src/**` |\n| --- | --- |\n| [B](b.md) | `x/**` |')).toEqual(
      [],
    )
  })
})

describe('globToRegExp', () => {
  it.each([
    ['src/**/cms/**', 'src/modules/news/cms/posts.ts', true],
    ['src/**/cms/**', 'src/cms/posts.ts', true],
    ['src/**/cms/**', 'src/modules/news/data/posts.ts', false],
    ['src/**/*.tsx', 'src/app/page.tsx', true],
    ['src/**/*.tsx', 'src/page.tsx', true],
    ['src/**/*.tsx', 'src/app/page.ts', false],
    ['next.config.*', 'next.config.js', true],
    ['next.config.*', 'src/next.config.js', false],
    ['.env*', '.env.local.example', true],
    ['src/**', 'src/a/b/c.ts', true],
  ])('%s against %s is %s', (glob, file, matches) => {
    expect(globToRegExp(glob).test(file)).toBe(matches)
  })
})

describe('rootLinks', () => {
  it('turns relative links into repo-root links and leaves the others', () => {
    const text =
      '[a](development.md#dry) [b](../../AGENTS.md) [c](https://x.dev) [d](#here) [e](/docs/x.md)'
    expect(rootLinks(text, 'docs/guidelines/security.md')).toBe(
      '[a](/docs/guidelines/development.md#dry) [b](/AGENTS.md) [c](https://x.dev) [d](#here) [e](/docs/x.md)',
    )
  })
})

describe('renderRule', () => {
  it('puts the globs in frontmatter, names the source, and keeps the text', () => {
    const rule = renderRule({
      source: 'docs/guidelines/payload-cms.md',
      paths: ['src/**/cms/**'],
      text: '# Payload\n\nSee [dev](development.md).\n\n',
    })
    expect(rule).toBe(
      "---\npaths:\n  - 'src/**/cms/**'\n---\n\n" +
        '<!-- Generated by scripts/agent-context.mjs from docs/guidelines/payload-cms.md. Edit that ' +
        'file, then run `npm run agent-context -- --write`. -->\n\n' +
        '# Payload\n\nSee [dev](/docs/guidelines/development.md).\n',
    )
    expect(hasPaths(rule)).toBe(true)
  })
})

describe('ruleName', () => {
  it('flattens the source path', () => {
    expect(ruleName('docs/guidelines/payload-cms.md')).toBe('docs--guidelines--payload-cms.md')
  })
})

describe('hasPaths', () => {
  it('reads frontmatter with Windows line endings', () => {
    expect(hasPaths("---\r\npaths:\r\n  - 'src/**'\r\n---\r\n\r\nText")).toBe(true)
    expect(hasPaths('# No frontmatter\r\n')).toBe(false)
  })
})

describe('importsOf', () => {
  it('finds @imports outside code', () => {
    const text = '@AGENTS.md\nSee `@README`.\n```\n@inside.md\n```\nAnd @docs/x.md here.'
    expect(importsOf(text)).toEqual(['AGENTS.md', 'docs/x.md'])
  })
})

describe('startupFiles', () => {
  const files = {
    'CLAUDE.md': '# Adapter\n\n@AGENTS.md\n@docs/guard.md\n',
    'AGENTS.md': 'one\ntwo\nthree\n',
    'docs/guard.md': 'a\nb\n',
    '.claude/rules/always.md': 'loaded\n',
    '.claude/rules/scoped.md': "---\npaths:\n  - 'src/**'\n---\n\nnot loaded\n",
  }
  const read = (file) => files[file] ?? null

  it('counts CLAUDE.md, its imports and the rules without paths, once each', () => {
    expect(startupFiles(read, ['.claude/rules/always.md', '.claude/rules/scoped.md'])).toEqual([
      { file: 'CLAUDE.md', lines: 4 },
      { file: 'AGENTS.md', lines: 3 },
      { file: 'docs/guard.md', lines: 2 },
      { file: '.claude/rules/always.md', lines: 1 },
    ])
  })

  it("counts what a path-scoped rule imports, which loads at start, but not the rule's own text", () => {
    const withImport = {
      ...files,
      '.claude/rules/scoped.md': "---\npaths:\n  - 'src/**'\n---\n\n@../../docs/big.md\n",
      'docs/big.md': 'x\ny\nz\n',
    }
    const readWith = (file) => withImport[file] ?? null
    expect(startupFiles(readWith, ['.claude/rules/scoped.md'])).toEqual([
      { file: 'CLAUDE.md', lines: 4 },
      { file: 'AGENTS.md', lines: 3 },
      { file: 'docs/guard.md', lines: 2 },
      { file: 'docs/big.md', lines: 3 },
    ])
  })
})
