describe('startupFiles', () => {
  const files = {
    'CLAUDE.md': '# Adapter\n\n@AGENTS.md\n@docs/guard.md\n',
    'AGENTS.md': 'one\ntwo\nthree\n',
    'docs/guard.md': 'a\nb\n',
    '.claude/rules/always.md': 'loaded\n',
    '.claude/rules/scoped.md': "---\npaths:\n  - 'src/**'\n---\n\nnot loaded\n",
  }
  const read = (file) => files[file] ?? null

  it('counts CLAUDE.md, its imports and the rules without paths, once each', () => {
    expect(startupFiles(read, ['.claude/rules/always.md', '.claude/rules/scoped.md'])).toEqual([
      { file: 'CLAUDE.md', lines: 4, tokens: countTokens(files['CLAUDE.md']) },
      { file: 'AGENTS.md', lines: 3, tokens: countTokens(files['AGENTS.md']) },
      { file: 'docs/guard.md', lines: 2, tokens: countTokens(files['docs/guard.md']) },
      {
        file: '.claude/rules/always.md',
        lines: 1,
        tokens: countTokens(files['.claude/rules/always.md']),
      },
    ])
  })

  it("counts what a path-scoped rule imports, which loads at start, but not the rule's own text", () => {
    const withImport = {
      ...files,
      '.claude/rules/scoped.md': "---\npaths:\n  - 'src/**'\n---\n\n@../../docs/big.md\n",
      'docs/big.md': 'x\ny\nz\n',
    }
    const readWith = (file) => withImport[file] ?? null
    const loaded = startupFiles(readWith, ['.claude/rules/scoped.md'])
    expect(loaded.map(({ file, lines }) => ({ file, lines }))).toEqual([
      { file: 'CLAUDE.md', lines: 4 },
      { file: 'AGENTS.md', lines: 3 },
      { file: 'docs/guard.md', lines: 2 },
      { file: 'docs/big.md', lines: 3 },
    ])
  })
})

describe('countTokens', () => {
  it('counts tokens of an OpenAI-style encoding, offline', () => {
    expect(countTokens('')).toBe(0)
    expect(countTokens('hello world')).toBe(2)
  })

  it('counts one long line for more than ten short ones, which a line count cannot tell', () => {
    const short = 'a\n'.repeat(10)
    const long = `${'The neighborhood association meets monthly. '.repeat(10)}\n`
    expect(countTokens(long)).toBeGreaterThan(countTokens(short))
  })

  it('has a budget that is a positive whole number of tokens', () => {
    expect(Number.isInteger(BUDGET_TOKENS)).toBe(true)
    expect(BUDGET_TOKENS).toBeGreaterThan(0)
  })
})

describe('parseKnowledgeMap', () => {
  const entry = { note: 'src/modules/events/README.md', paths: ['src/modules/events/**'] }

  it('reads each note with the paths it describes', () => {
    expect(parseKnowledgeMap(JSON.stringify([entry]))).toEqual([
      { source: entry.note, paths: entry.paths, origin: 'docs/knowledge/map.json' },
    ])
  })

  it('refuses a map it would otherwise misread, naming the entry', () => {
    const bad = (value) => () => parseKnowledgeMap(JSON.stringify(value), 'map.json')
    expect(() => parseKnowledgeMap('{', 'map.json')).toThrow('map.json')
    expect(bad({})).toThrow('a list')
    expect(bad([{ note: 'a.md' }])).toThrow('entry 1')
    expect(bad([{ note: 'a.md', paths: [] }])).toThrow('entry 1')
    expect(bad([{ note: 'a.md', paths: [3] }])).toThrow('entry 1')
    expect(bad([{ note: 'a.txt', paths: ['a/**'] }])).toThrow('entry 1')
  })
})

/** A throwaway git repository holding `files`, so `run` sees tracked files as in CI. */
function repo(files) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-context-'))
  const base = {
    'docs/guidelines/README.md':
      '| Reference | Loads by itself when the work touches |\n| - | - |\n',
    'CLAUDE.md': '# Adapter\n',
    ...files,
  }
  for (const [file, text] of Object.entries(base)) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true })
    fs.writeFileSync(path.join(root, file), text)
  }
  execFileSync('git', ['init', '-q'], { cwd: root })
  execFileSync('git', ['add', '-A'], { cwd: root })
  return root
}

describe('the parsers PR Policy imports', () => {
  it('load in a checkout with no installed packages, so without the token counter', () => {
    // The PR Policy workflow runs .github/scripts/knowledge-sync.mjs without `npm ci` (#737)
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-context-bare-'))
    const copies = [
      'scripts/agent-context-maps.mjs',
      'scripts/behavior-change.mjs',
      '.github/scripts/knowledge-sync.mjs',
      '.github/scripts/pr-body.mjs',
    ]
    for (const file of copies) {
      fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true })
      fs.copyFileSync(file, path.join(root, file))
    }
    const entry = pathToFileURL(path.join(root, '.github/scripts/knowledge-sync.mjs')).href
    const output = execFileSync(
      process.execPath,
      [
        '--input-type=module',
        '-e',
        `const m = await import(${JSON.stringify(entry)}); console.log(typeof m.MIN_REASON_LENGTH)`,
      ],
      { cwd: root, encoding: 'utf8' },
    )
    expect(output.trim()).toBe('number')
  })

  it('are the same functions agent-context.mjs exports', async () => {
    const maps = await import('./agent-context-maps.mjs')
    expect(parseLoadMap).toBe(maps.parseLoadMap)
    expect(parseKnowledgeMap).toBe(maps.parseKnowledgeMap)
    expect(globToRegExp).toBe(maps.globToRegExp)
  })
})

describe('run, with the session-start budget', () => {
  const budgetProblems = (root, options) =>
    run(root, options).problems.filter((problem) => problem.includes('session start'))

  it('fails over the token budget and says the count is approximate', () => {
    const [problem] = budgetProblems(repo({ 'CLAUDE.md': 'word '.repeat(200) }), {
      budgetTokens: 100,
    })
    expect(problem).toMatch(/loads \d+ tokens/)
    expect(problem).toContain('over the budget of 100')
    expect(problem).toMatch(/approximate/i)
  })

  it('passes under the token budget however many lines there are', () => {
    const root = repo({ 'CLAUDE.md': 'a\n'.repeat(400) })
    const { total, loaded } = run(root, { budgetTokens: 5000 })
    expect(loaded[0].lines).toBe(400)
    expect(total).toBe(loaded[0].tokens)
    expect(budgetProblems(root, { budgetTokens: 5000 })).toEqual([])
  })

  it('uses the default budget when none is given', () => {
    expect(budgetProblems(repo({}))).toEqual([])
  })
})

describe('run, with a knowledge map', () => {
  const map = JSON.stringify([{ note: 'src/mod/README.md', paths: ['src/mod/**'] }])
  const files = {
    'docs/knowledge/map.json': map,
    'src/mod/README.md': '# Mod\n\nSee [x](../../docs/x.md).\n',
    'src/mod/code.ts': 'export {}\n',
  }
  const rule = '.claude/rules/generated/src--mod--README.md'
  // The fixture's load map is empty on purpose; that problem is not what these tests are about
  const problemsOf = (root, options) =>
    run(root, options).problems.filter((problem) => !problem.includes('no load map'))

  it('writes a path-scoped rule for each note, then finds it current', () => {
    const root = repo(files)
    expect(problemsOf(root, { write: true })).toEqual([])
    const text = fs.readFileSync(path.join(root, rule), 'utf8')
    expect(text).toContain("paths:\n  - 'src/mod/**'")
    expect(text).toContain('](/docs/x.md)')
    expect(problemsOf(root)).toEqual([])
  })

  it('fails when the rule is out of date or the note is gone', () => {
    const root = repo(files)
    problemsOf(root, { write: true })
    fs.appendFileSync(path.join(root, 'src/mod/README.md'), 'More.\n')
    expect(problemsOf(root)).toEqual([`${rule} is out of date`])

    fs.rmSync(path.join(root, 'src/mod/README.md'))
    expect(problemsOf(root)).toContain(
      "docs/knowledge/map.json lists src/mod/README.md, which doesn't exist",
    )
  })

  it('fails when a pattern matches no tracked file', () => {
    const root = repo({
      ...files,
      'docs/knowledge/map.json': JSON.stringify([
        { note: 'src/mod/README.md', paths: ['src/gone/**'] },
      ]),
    })
    expect(problemsOf(root, { write: true })).toEqual([
      'src/mod/README.md: `src/gone/**` matches no file in the repository',
    ])
  })
})
