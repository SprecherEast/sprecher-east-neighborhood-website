/**
 * The catalog (#1462, choice B1): the graph grouped into clusters, one readable page, read on
 * demand and never loaded at session start. Made from the graph alone, so it cannot drift from it.
 */

const AREA_LABEL = { module: 'module', 'platform-area': 'shared area', feature: 'feature' }

const SENTENCE_LIMIT = 140

/** The first sentence of a text, cut at a word when it runs long, ending with a full stop. */
function firstSentence(text) {
  const first = text.split(/(?<=[.!?])\s/)[0].trim()
  const cut =
    first.length <= SENTENCE_LIMIT
      ? first
      : `${first.slice(0, SENTENCE_LIMIT).replace(/\s+\S*$/, '')}…`
  return cut.replace(/[.…]?$/, (end) => (end === '…' ? '…' : '.'))
}

const byName = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0)
const code = (text) => `\`${text}\``

/** What a module or area holds, as a short sentence: counts of the kinds of thing it contains. */
function holdings(graph, id, typeOf) {
  const counts = new Map()
  for (const edge of graph.edges) {
    if (edge.from === id && edge.type === 'contains') {
      const type = typeOf.get(edge.to)
      counts.set(type, (counts.get(type) ?? 0) + 1)
    }
  }
  const labels = {
    screen: ['screen', 'screens'],
    'page-cluster': ['screen group', 'screen groups'],
    collection: ['content type', 'content types'],
    global: ['global', 'globals'],
    endpoint: ['endpoint', 'endpoints'],
    'mcp-tool': ['AI agent tool', 'AI agent tools'],
    job: ['job', 'jobs'],
    'shared-component': ['component', 'components'],
    feature: ['feature', 'features'],
    'business-rule': ['rule', 'rules'],
    block: ['block', 'blocks'],
  }
  return [...counts]
    .filter(([type]) => labels[type])
    .sort(([a], [b]) => (labels[a][1] < labels[b][1] ? -1 : 1))
    .map(([type, n]) => `${n} ${labels[type][n === 1 ? 0 : 1]}`)
    .join(', ')
}

const section = (title, lines) => (lines.length === 0 ? [] : [`## ${title}`, '', ...lines, ''])

/** The catalog as Markdown text. */
export function renderCatalog(graph) {
  const typeOf = new Map(graph.nodes.map((node) => [node.id, node.type]))
  const of = (...types) => graph.nodes.filter((node) => types.includes(node.type)).sort(byName)
  const line = (node, label, tail = '') =>
    `- ${label}${node.summary ? ` ${firstSentence(node.summary)}` : ''}${tail} ${code(node.path)}`

  const areas = of('module', 'platform-area', 'feature').map((node) => {
    const held = holdings(graph, node.id, typeOf)
    return line(node, `**${node.name}** (${AREA_LABEL[node.type]}):`, held ? ` Holds ${held}.` : '')
  })
  const contentTypes = of('collection', 'global').map((node) => {
    const references = graph.edges.filter(
      (e) => e.from === node.id && e.type === 'references',
    ).length
    return `- ${code(node.name)} (${node.type}): ${node.fields.length} fields${references ? `, points at ${references} other content types` : ''}. ${code(node.path)}`
  })
  const tools = of('mcp-tool').map((node) => line(node, `${code(node.name)}:`))
  const jobs = of('job').map((node) => line(node, `${code(node.name)}:`))
  const scheduled = of('scheduled-task').map((node) => line(node, `**${node.name}**:`))
  const clusters = of('page-cluster').map((node) => line(node, `${code(node.name)}:`))
  const kinds = [
    ['skill', 'Agent skills'],
    ['subagent', 'AI agents'],
    ['role', 'Role guides'],
    ['guideline', 'Guidelines'],
    ['process-doc', 'Process documents'],
    ['ci-workflow', 'CI workflows'],
  ]
  const work = kinds.flatMap(([type, title]) => {
    const nodes = of(type)
    return nodes.length === 0
      ? []
      : [`- **${title}** (${nodes.length}): ${nodes.map((n) => code(n.name)).join(', ')}`]
  })
  const counted = ['decision', 'rule', 'check']
    .map((type) => [type, of(type).length])
    .filter(([, n]) => n > 0)
    .map(
      ([type, n]) =>
        `${n} ${type === 'check' ? 'checks' : `${type === 'decision' ? 'decision records' : 'rule files'}`}`,
    )
  const libraries = of('library').map((n) => code(n.name))

  return [
    '# System map catalog',
    '',
    `> Generated by \`npm run knowledge:map\` from \`docs/knowledge/graph.json\`. Do not edit by hand: change the code or the notes, then run the command. Read it on demand; it is not loaded at session start.`,
    '',
    `The graph holds ${graph.nodes.length} nodes and ${graph.edges.length} relationships on ${graph.layers.length} layers. This page groups them; the graph file and the map page hold every field, relationship and watch-out.`,
    '',
    ...section('Modules and shared areas', areas),
    ...section('Content types', contentTypes),
    ...section('Screen groups', clusters),
    ...section('AI agent tools', tools),
    ...section('Jobs', jobs),
    ...section('Scheduled tasks', scheduled),
    ...section('How we work', [
      ...work,
      ...(counted.length ? [`- Also: ${counted.join(', ')}.`] : []),
    ]),
    ...section('Libraries the source imports', libraries.length ? [libraries.join(', ')] : []),
  ]
    .join('\n')
    .replace(/\n+$/, '\n')
}
