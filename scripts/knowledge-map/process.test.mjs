import { describe, expect, it } from 'vitest'

import { PROCESS_GROUPS, buildProcess, classify } from './process.mjs'

describe('classify', () => {
  it.each([
    ['.agents/skills/wrapped/SKILL.md', 'skill'],
    ['.agents/skills/wrapped/references/x.md', null],
    ['.claude/agents/worker.md', 'subagent'],
    ['docs/roles/worker.md', 'role'],
    ['docs/roles/README.md', null],
    ['docs/architecture/decisions/0022-notes.md', 'decision'],
    ['docs/architecture/decisions/README.md', null],
    ['docs/guidelines/security.md', 'guideline'],
    ['docs/guidelines/frontend-patterns/forms.md', 'guideline'],
    ['docs/process/waits-for-owner.md', 'process-doc'],
    ['.claude/rules/claude-code-setup.md', 'rule'],
    ['.claude/rules/generated/docs--guidelines--security.md', 'rule'],
    ['docs/product/vision.md', null],
  ])('%s is %s', (file, type) => {
    expect(classify(file)).toBe(type)
  })
})

const docs = [
  {
    path: '.agents/skills/wrapped/SKILL.md',
    text: '---\nname: wrapped\ndescription: Post-merge wrap-up, run right after you merge a PR.\n---\n\n# Wrapped: after a merge\n\nSee [`pr-review`](../pr-review/SKILL.md) and the [worker role](../../../docs/roles/worker.md).\n',
  },
  {
    path: '.agents/skills/pr-review/SKILL.md',
    text: '---\nname: pr-review\ndescription: Independent review of a pull request.\n---\n\n# PR review\n\nText.\n',
  },
  {
    path: 'docs/roles/worker.md',
    text: '# Worker: Sprecher East\n\n> Role guide ([all roles](README.md)).\n\n## Mission\n\nYou finish one Ready issue, from claim to merge, and nothing else.\n',
  },
  {
    path: '.claude/agents/worker.md',
    text: "---\nname: worker\ndescription: 'Does one Ready issue from start to merge.'\nmodel: sonnet\n---\n\nRead your role guide, [`docs/roles/worker.md`](../../docs/roles/worker.md).\n",
  },
  {
    path: 'docs/architecture/decisions/0022-notes.md',
    text: '# 0022: Knowledge notes have front matter\n\n- **Date:** 2026-11-24\n- **Status:** Accepted\n\n## Context\n\nText.\n',
  },
  {
    path: '.claude/rules/generated/src--modules--demo--README.md',
    text: "---\npaths:\n  - 'src/modules/demo/**'\n---\n\n<!-- Generated by scripts/agent-context.mjs from src/modules/demo/README.md. Edit that file. -->\n\n# Demo\n",
  },
]
const files = docs.map((d) => d.path)

describe('buildProcess', () => {
  const { nodes, edges } = buildProcess({ docs, files, siteId: 'site:sprecher-east' })
  const byId = (id) => nodes.find((n) => n.id === id)
  const edge = (from, to, type) =>
    edges.find((e) => e.from === from && e.to === to && e.type === type)

  it('makes a node of each document by its kind, named and summarised from its front matter or text', () => {
    expect(byId('skill:wrapped')).toMatchObject({
      type: 'skill',
      name: 'wrapped',
      summary: 'Post-merge wrap-up, run right after you merge a PR.',
      path: '.agents/skills/wrapped/SKILL.md',
    })
    expect(byId('role:worker')).toMatchObject({
      type: 'role',
      name: 'Worker: Sprecher East',
      summary: 'You finish one Ready issue, from claim to merge, and nothing else.',
    })
    expect(byId('subagent:worker')).toMatchObject({
      type: 'subagent',
      summary: 'Does one Ready issue from start to merge.',
    })
  })

  it('reads the date and status of a decision record', () => {
    expect(byId('decision:0022-notes').facts).toEqual([
      { label: 'Date', value: '2026-11-24' },
      { label: 'Status', value: 'Accepted' },
    ])
    expect(byId('decision:0022-notes').name).toBe('0022: Knowledge notes have front matter')
  })

  it('makes a rule of a generated rule file, saying when it loads and mirroring its source', () => {
    expect(byId('rule:src--modules--demo--README')).toMatchObject({
      type: 'rule',
      facts: [{ label: 'Loads when work touches', value: 'src/modules/demo/**' }],
    })
    expect(
      edges.find((e) => e.from === 'rule:src--modules--demo--README' && e.type === 'mirrors').to,
    ).toBe('path:src/modules/demo/README.md')
  })

  it('holds the documents in groups under one how-we-work heading under the site', () => {
    expect(edge('site:sprecher-east', 'group:how-we-work', 'contains')).toBeDefined()
    expect(edge('group:how-we-work', 'group:skills', 'contains')).toBeDefined()
    expect(edge('group:skills', 'skill:wrapped', 'contains')).toBeDefined()
    expect(edge('group:roles', 'role:worker', 'contains')).toBeDefined()
    expect(nodes.filter((n) => n.type === 'group')).toHaveLength(PROCESS_GROUPS.length + 1)
  })

  it('has a skill or an agent mention the documents it links', () => {
    expect(
      edges.find(
        (e) => e.from === 'skill:wrapped' && e.to === 'path:.agents/skills/pr-review/SKILL.md',
      ),
    ).toMatchObject({ type: 'mentions' })
    expect(
      edges.find((e) => e.from === 'subagent:worker' && e.to === 'path:docs/roles/worker.md'),
    ).toMatchObject({ type: 'mentions' })
  })
})
