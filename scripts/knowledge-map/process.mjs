/**
 * How we work, as nodes (#1462): the agent skills, subagents, role guides, decision records,
 * guidelines, process documents and rule files, each typed by where it lives and described by its
 * front matter or first paragraph, held in groups under one heading. The links between documents
 * become relationships. Pure.
 */
import path from 'node:path'

import { parseFrontmatter, splitFrontmatter } from '../frontmatter.mjs'
import { makeEdge, makeNode, nodeId } from './graph.mjs'
import { linkedPaths } from './notes.mjs'

const SUMMARY_LIMIT = 240

/** The groups, in the order they are drawn: the type they hold, a name, and the folder that opens the group. */
export const PROCESS_GROUPS = [
  { key: 'skills', type: 'skill', name: 'Agent skills', path: '.agents/skills' },
  { key: 'subagents', type: 'subagent', name: 'AI agents', path: '.claude/agents' },
  { key: 'roles', type: 'role', name: 'Role guides', path: 'docs/roles' },
  {
    key: 'decisions',
    type: 'decision',
    name: 'Decision records',
    path: 'docs/architecture/decisions',
  },
  { key: 'guidelines', type: 'guideline', name: 'Guidelines', path: 'docs/guidelines' },
  { key: 'process', type: 'process-doc', name: 'Process documents', path: 'docs/process' },
  { key: 'rules', type: 'rule', name: 'Agent rules', path: '.claude/rules' },
  { key: 'ci', type: 'ci-workflow', name: 'CI workflows', path: '.github/workflows' },
  {
    key: 'scheduled-tasks',
    type: 'scheduled-task',
    name: 'Scheduled tasks',
    path: 'docs/knowledge/scheduled-tasks.md',
  },
]

export const HOW_WE_WORK_ID = nodeId('group', 'how-we-work')

const PATTERNS = [
  ['skill', /^\.agents\/skills\/[^/]+\/SKILL\.md$/],
  ['subagent', /^\.claude\/agents\/[^/]+\.md$/],
  ['role', /^docs\/roles\/(?!README\.md$)[^/]+\.md$/],
  ['decision', /^docs\/architecture\/decisions\/(?!README\.md$)[^/]+\.md$/],
  ['guideline', /^docs\/guidelines\/(?!README\.md$).+\.md$/],
  ['process-doc', /^docs\/process\/(?!README\.md$)[^/]+\.md$/],
  ['rule', /^\.claude\/rules\/.+\.md$/],
]

/** The kind of document a path is, or null when it is none of the kinds the map holds. */
export function classify(file) {
  return PATTERNS.find(([, pattern]) => pattern.test(file))?.[0] ?? null
}

const clean = (text) =>
  text
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[*_]{1,2}([^*_]+)[*_]{1,2}/g, '$1')
    .replace(/\s+/g, ' ')
    .trim()

const cut = (text) =>
  text.length <= SUMMARY_LIMIT ? text : `${text.slice(0, SUMMARY_LIMIT).replace(/\s+\S*$/, '')}…`

/** The first paragraph of prose: not a heading, a quote, a list, a table or a comment. */
function firstParagraph(body) {
  const lines = body.replace(/<!--[\s\S]*?-->/g, '').split('\n')
  const out = []
  for (const line of lines) {
    const text = line.trim()
    const prose = text && !/^(#|>|[-*] |\d+\. |\||```|---)/.test(text)
    if (prose) out.push(text)
    else if (out.length > 0) break
  }
  return cut(clean(out.join(' ')))
}

const titleOf = (body) => /^# (.+)$/m.exec(body)?.[1]?.trim() ?? ''

/** `{ date, status }` facts of a decision record, from its `- **Date:**` lines. */
function decisionFacts(body) {
  return ['Date', 'Status']
    .map((label) => [
      label,
      new RegExp(`^- \\*\\*${label}:\\*\\*\\s*(.+)$`, 'm').exec(body)?.[1]?.trim(),
    ])
    .filter(([, value]) => value)
    .map(([label, value]) => ({ label, value: clean(value) }))
}

function keyOf(type, file) {
  if (type === 'skill') return path.posix.basename(path.posix.dirname(file))
  return path.posix.basename(file, '.md')
}

function describe(type, file, text) {
  const { rest } = splitFrontmatter(text)
  const data = parseFrontmatter(text)
  const body = rest
  const title = titleOf(body)
  const key = keyOf(type, file)
  const description = typeof data.description === 'string' ? cut(clean(data.description)) : ''
  const base = { name: key, summary: description || firstParagraph(body), facts: [] }
  if (type === 'role') return { ...base, name: title || key }
  if (type === 'decision')
    return {
      ...base,
      name: title || key,
      summary:
        firstParagraph(
          body
            .split('\n## ')
            .slice(1)
            .join('\n## ')
            .replace(/^[^\n]*\n/, ''),
        ) || base.summary,
      facts: decisionFacts(body),
    }
  if (type === 'rule') {
    const paths = Array.isArray(data.paths) ? data.paths.join(', ') : ''
    return {
      ...base,
      name: title || key,
      facts: paths ? [{ label: 'Loads when work touches', value: paths }] : [],
    }
  }
  if (type === 'guideline' || type === 'process-doc') return { ...base, name: title || key }
  return base
}

const MIRROR = /Generated by [^\n]*? from (\S+?)\.\s/

/** `{ nodes, edges, gaps }`; `docs` are `{ path, text }` of every Markdown file, `files` all repository files. */
export function buildProcess({ docs, files, siteId }) {
  const nodes = [
    makeNode({
      id: HOW_WE_WORK_ID,
      type: 'group',
      name: 'How we work',
      summary:
        'The skills, AI agents, roles, decisions, guidelines and rules that say how a change is made.',
      path: 'AGENTS.md',
    }),
  ]
  const edges = [makeEdge({ from: siteId, to: HOW_WE_WORK_ID, type: 'contains' })]
  for (const group of PROCESS_GROUPS) {
    const id = nodeId('group', group.key)
    nodes.push(
      makeNode({ id, type: 'group', name: group.name, path: group.path, module: HOW_WE_WORK_ID }),
    )
    edges.push(makeEdge({ from: HOW_WE_WORK_ID, to: id, type: 'contains' }))
  }
  const groupOf = new Map(PROCESS_GROUPS.map((group) => [group.type, nodeId('group', group.key)]))

  for (const doc of docs) {
    const type = classify(doc.path)
    if (!type) continue
    const id = nodeId(type, keyOf(type, doc.path))
    const { name, summary, facts } = describe(type, doc.path, doc.text)
    nodes.push(makeNode({ id, type, name, summary, path: doc.path, module: HOW_WE_WORK_ID, facts }))
    edges.push(makeEdge({ from: groupOf.get(type), to: id, type: 'contains' }))
    for (const link of linkedPaths(doc.text, doc.path, files)) {
      if (link !== doc.path)
        edges.push(makeEdge({ from: id, to: `path:${link}`, type: 'mentions' }))
    }
    const mirror = type === 'rule' ? MIRROR.exec(doc.text)?.[1] : null
    if (mirror) edges.push(makeEdge({ from: id, to: `path:${mirror}`, type: 'mirrors' }))
  }
  return { nodes, edges, gaps: [] }
}
